#!/usr/bin/env python3
"""Generate an allocation-free, fixed-size OSQP C solver (20 steps, four states, two inputs)."""
import pathlib
import numpy as np
import scipy.sparse as sp
import osqp

ROOT=pathlib.Path(__file__).resolve().parents[2]
N=20
NX=4
NU=2
NV=N*(NX+NU)
NC=N*NX+NV

def matrices():
    # Variables: [e_y,e_yaw,v,delta] for k=1..N, then [delta_rate,a] for k=0..N-1.
    A=sp.lil_matrix((NC,NV))
    for k in range(N):
        for j in range(NX):A[4*k+j,4*k+j]=1
        if k:
            for j in range(NX):A[4*k+j,4*(k-1)+j]=-1
            A[4*k,4*(k-1)+1]=-.01
            A[4*k+1,4*(k-1)+3]=-.01
        A[4*k+2,N*NX+2*k+1]=-.05
        A[4*k+3,N*NX+2*k]=-.05
    for i in range(NV):A[N*NX+i,i]=1
    weights=np.tile([24.,16.,3.,.5],N).tolist()+np.tile([.08,.15],N).tolist()
    P=sp.diags(weights,format='csc')
    return P,A.tocsc()

def main():
    P,A=matrices()
    solver=osqp.OSQP()
    lower=np.full(NC,-1.);upper=np.full(NC,1.)
    lower[:N*NX]=0;upper[:N*NX]=0
    solver.setup(P=P,q=np.zeros(NV),A=A,l=lower,u=upper,verbose=False,
                 max_iter=100,eps_abs=1e-3,eps_rel=1e-3,check_termination=5,
                 polishing=False,warm_starting=True)
    dest=ROOT/'robot/android/maxbot/src/main/cpp/osqp_generated'
    solver.codegen(str(dest),parameters='matrices',extension_name=None,force_rewrite=True,
                   printing_enable=False,profiling_enable=False,interrupt_enable=False)
    # Runtime reconstructs A values in this exact CSC order; no dynamic sparsity changes.
    meta=ROOT/'robot/android/maxbot/src/main/cpp/mpc_structure.h'
    def arr(name,data):return 'static const int '+name+'[] = {'+','.join(map(str,data))+'};\n'
    meta.write_text('// Generated by tools/maxbot/generate_mpc.py\n#pragma once\n'+
                    arr('MPC_A_ROWS',A.indices)+arr('MPC_A_COLS',A.indptr)+
                    f'#define MPC_A_NNZ {A.nnz}\n')
    print(f'Generated native OSQP solver: {NV} variables, {NC} constraints, {A.nnz} A entries')

if __name__=='__main__':main()
